function inferMetadata(name, index) {
  const upper = name.toUpperCase();
  let category = 'General Health';
  let dosageForm = 'Medicine';
  let price = 45;
  let rxRequired = true;
  let description = `${name} is formulated for effective treatment and wellness recovery.`;

  if (upper.includes('INJ') || upper.includes('INJECTION')) {
    category = 'Injections & Infusions';
    dosageForm = 'Injection';
    price = 120 + ((index * 7) % 180);
    rxRequired = true;
    description = `Sterile injectible formulation for rapid therapeutic relief.`;
  } else if (upper.includes('SYP') || upper.includes('SYRUP') || upper.includes('SUSP') || upper.includes('TONIC')) {
    category = 'Syrups & Suspensions';
    dosageForm = 'Syrup';
    price = 65 + ((index * 5) % 110);
    rxRequired = !upper.includes('MULTIVITAMIN') && !upper.includes('CHYWANPRASH');
    description = `Oral liquid formulation for effective symptom relief.`;
  } else if (upper.includes('CAP') || upper.includes('CAPS') || upper.includes('SOFT GEL')) {
    category = 'Capsules';
    dosageForm = 'Capsule';
    price = 55 + ((index * 6) % 140);
    rxRequired = true;
    description = `High-absorption capsule formulated for sustained relief.`;
  } else if (upper.includes('DT') || upper.includes('TAB') || upper.includes('TABLET')) {
    category = 'Tablets';
    dosageForm = 'Tablet';
    price = 35 + ((index * 4) % 120);
    rxRequired = true;
    description = `Effective therapeutic tablet formulation.`;
  } else if (upper.includes('DROP') || upper.includes('DROPS')) {
    category = 'Eye, Ear & Nasal Drops';
    dosageForm = 'Drops';
    price = 45 + ((index * 3) % 75);
    rxRequired = true;
    description = `Targeted liquid drops for ENT or ophthalmic care.`;
  } else if (upper.includes('CREAM') || upper.includes('OINT') || upper.includes('GEL') || upper.includes('JELLY')) {
    category = 'Ointments & Topicals';
    dosageForm = 'Topical Application';
    price = 60 + ((index * 4) % 95);
    rxRequired = upper.includes('CLOB') || upper.includes('DERM') || upper.includes('CORT');
    description = `Topical relief formula designed to soothe skin and inflammation.`;
  } else if (upper.includes('SOAP') || upper.includes('SHAMPOO') || upper.includes('LOTION') || upper.includes('CONDOM') || upper.includes('CARD') || upper.includes('POWDER') || upper.includes('SACHET')) {
    category = 'Personal Care & Wellness';
    dosageForm = 'Wellness / OTC';
    price = 50 + ((index * 5) % 150);
    rxRequired = false;
    description = `Everyday wellness and hygiene essential product.`;
  }

  return { category, price, rxRequired, dosageForm, description };
}

async function seed() {
  console.log(`\n🚀 Seeding ${RAW_MEDICINES.length} medicines into Firestore collection 'Medicinename'...`);
  const batchSize = 400;
  let total = 0;

  for (let i = 0; i < RAW_MEDICINES.length; i += batchSize) {
    const chunk = RAW_MEDICINES.slice(i, i + batchSize);
    const batch = writeBatch(db);

    chunk.forEach((name, idx) => {
      const overallIdx = i + idx;
      const id = `med_${overallIdx + 1}`;
      const meta = inferMetadata(name, overallIdx);
      const docRef = doc(db, 'Medicinename', id);

      batch.set(docRef, {
        id,
        name: name.trim(),
        nameLower: name.trim().toLowerCase(),
        category: meta.category,
        price: meta.price,
        formattedPrice: `₹${meta.price.toFixed(2)}`,
        rxRequired: meta.rxRequired,
        dosageForm: meta.dosageForm,
        description: meta.description,
        updatedAt: new Date().toISOString(),
      }, { merge: true });
    });

    await batch.commit();
    total += chunk.length;
    console.log(`✅ Uploaded batch ${Math.floor(i / batchSize) + 1}: ${total}/${RAW_MEDICINES.length} medicines`);
  }

  console.log(`\n🎉 Successfully seeded all ${total} medicines into Firestore collection 'Medicinename'!\n`);
  process.exit(0);
}

seed().catch(err => {
  console.error("❌ Seeding failed:", err);
  process.exit(1);
});
